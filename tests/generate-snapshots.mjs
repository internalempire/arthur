// Regenerates tests/snapshots.js from the current model. Run deliberately, and
// review the diff: a change here is a change in behaviour, not a formality.
//
//   node tests/generate-snapshots.mjs
import { writeFileSync } from 'node:fs';
import { Simulator } from '../src/model/simulator.js';
import { SCENARIOS } from '../src/model/scenarios.js';

const rows = [];
for (const sc of SCENARIOS) {
  const s = new Simulator();
  s.applyScenario(sc);
  s.advance(30, true);
  const m = s.metrics;
  rows.push(`  '${sc.id}': { co: ${m.co.toFixed(2)}, map: ${m.map.toFixed(1)}, cvp: ${m.cvp.toFixed(2)}, `
    + `papMean: ${m.papMean.toFixed(1)}, paop: ${m.paop.toFixed(2)}, pvr: ${m.pvrCoefficientWood.toFixed(2)} },`);
}
writeFileSync(new URL('./snapshots.js', import.meta.url),
  `// Generated by tests/generate-snapshots.mjs — do not edit by hand.\n`
  + `// Steady state after 30 s of simulated time from each preset.\n`
  + `export const SNAPSHOTS = {\n${rows.join('\n')}\n};\n`);
console.log(`wrote ${rows.length} snapshots`);
